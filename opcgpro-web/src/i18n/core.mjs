export function isSupportedLocale(value) {
  return SUPPORTED_LOCALES.includes(value);
}

export function translateText(value, locale) {
  if (locale === DEFAULT_LOCALE || !value) return value;

  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const source = value.slice(leading.length, value.length - trailing.length || undefined);
  if (!source) return value;

  const exact = MESSAGES[locale]?.[source];
  if (exact) return `${leading}${exact}${trailing}`;

  for (const [pattern, replacement] of templateRules[locale] ?? []) {
    if (pattern.test(source)) {
      return `${leading}${source.replace(pattern, replacement)}${trailing}`;
    }
  }

  return value;
}
